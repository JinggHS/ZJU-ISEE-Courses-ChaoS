# ----------------------------
theta = -5 * np.pi / 6
phi = 0.0
state = np.array([1.0 + 0.0j, 1.0j]) / np.sqrt(2)


# 1. 定义哈达玛门 H
H = np.array(
    [
        [1.0, 1.0],
        [1.0, -1.0],
    ],
    dtype=complex,
) / np.sqrt(2)


# 2. 定义相移门 P_theta 和 P_(pi/2 + phi)
P_theta = np.array(
    [
        [1.0 + 0.0j, 0.0 + 0.0j],
        [0.0 + 0.0j, np.exp(1.0j * theta)],
    ],
    dtype=complex,
)

P_phi = np.array(
    [
        [1.0 + 0.0j, 0.0 + 0.0j],
        [0.0 + 0.0j, np.exp(1.0j * (np.pi / 2 + phi))],
    ],
    dtype=complex,
)


# 3. 依次作用量子门：U = P_(pi/2+phi) H P_theta H
state = np.dot(H, state)
state = np.dot(P_theta, state)
state = np.dot(H, state)
state = np.dot(P_phi, state)


# 4. 计算并输出基态和第一激发态的测量概率
prob_0 = abs(state[0]) ** 2
prob_1 = abs(state[1]) ** 2

print("最终态 =")
print(state)
print(f"最终基态概率   (|0>): {prob_0 * 100:.2f}%")
print(f"最终激发态概率 (|1>): {prob_1 * 100:.2f}%")
